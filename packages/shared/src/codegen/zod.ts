import { modelRefOf, type Field, type FieldType, type PrimitiveType } from '../api';
import type { CanvasDoc } from '../canvas';
import { roleText } from '../feature-scope';
import type { CodegenOptions } from './options';
import { dependencyOrder } from './order';
import { uniqueName } from './python';
import { jsDoc, tsString as str } from './typescript';

/* ============================================================
 * Zod 4 schemas plus inferred TypeScript types from the API models, e.g. to validate
 * request and response bodies in a TypeScript client or server. Keys are the API names, so
 * parsed objects match the OpenAPI spec. Models come after the models they use; a reference
 * to a later model (a cycle) is a getter, which Zod 4 resolves lazily.
 * ============================================================ */

/** Names a module-level `const` can't take, plus the `z` import */
const RESERVED = new Set(
  (
    'break case catch class const continue debugger default delete do else enum export extends false finally for ' +
    'function if import in instanceof new null return super switch this throw true try typeof var void while with ' +
    'yield let static implements interface package private protected public await arguments eval undefined NaN Infinity z'
  ).split(' '),
);

/** `name` when it's an identifier, else a quoted key */
const key = (name: string) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : str(name));

function primitive(type: PrimitiveType): string {
  if (type.enum?.length) {
    if (type.type === 'string') return `z.enum([${type.enum.map(str).join(', ')}])`;
    // Numbers stay numbers; anything else is compared as written
    const values = type.enum.map((v) => (/^-?\d+(\.\d+)?$/.test(v) ? v : str(v)));
    return values.length === 1 ? `z.literal(${values[0]})` : `z.literal([${values.join(', ')}])`;
  }
  switch (type.type) {
    case 'integer':
      return type.format === 'int32' ? 'z.int32()' : 'z.int()';
    case 'number':
      return 'z.number()';
    case 'boolean':
      return 'z.boolean()';
  }
  switch (type.format) {
    case 'uuid':
      return 'z.uuid()';
    case 'email':
      return 'z.email()';
    case 'uri':
      return 'z.url()';
    case 'date':
      return 'z.iso.date()';
    case 'date-time':
      // RFC 3339, as OpenAPI's date-time: `Z` or an offset
      return 'z.iso.datetime({ offset: true })';
    default:
      return 'z.string()';
  }
}

function zodType(type: FieldType, names: ReadonlyMap<string, string>): string {
  switch (type.kind) {
    case 'primitive':
      return primitive(type);
    case 'ref':
      return names.get(type.modelId)!;
    case 'array':
      return `z.array(${zodType(type.items, names)})`;
  }
}

function fieldLines(f: Field, names: ReadonlyMap<string, string>, forward: boolean): string[] {
  let type = zodType(f.type, names);
  if (f.nullable) type += '.nullable()';
  if (!f.required) type += '.optional()';
  const docs = jsDoc([...(f.description?.trim() ? [f.description] : []), ...(f.example !== undefined ? [`@example ${f.example}`] : [])], '  ');
  // A model defined further down is only there once the module has run: a getter reads it lazily
  const body = forward ? [`  get ${key(f.name)}() {`, `    return ${type};`, '  },'] : [`  ${key(f.name)}: ${type},`];
  return [...docs, ...body];
}

/** The doc's API models as Zod 4 schemas with inferred types */
export function toZod(doc: Pick<CanvasDoc, 'models'>, options: CodegenOptions = {}): string {
  const used = new Set<string>();
  const names = new Map(doc.models.map((m) => [m.id, uniqueName(RESERVED.has(m.name) ? `${m.name}_` : m.name, used)]));

  const defined = new Set<string>();
  const schemas = dependencyOrder(doc.models).map((model) => {
    const name = names.get(model.id)!;
    const fields = model.fields.flatMap((f) => {
      const ref = modelRefOf(f.type);
      return fieldLines(f, names, ref !== undefined && names.has(ref) && !defined.has(ref));
    });
    defined.add(model.id);
    const role = options.roles?.get(`model:${model.id}`);
    return [
      ...(options.featureName ? [`// ${roleText(role, options.featureName)}`] : []),
      ...jsDoc(model.description?.trim() ? [model.description] : [], ''),
      fields.length ? `export const ${name} = z.object({\n${fields.join('\n')}\n});` : `export const ${name} = z.object({});`,
      `export type ${name} = z.infer<typeof ${name}>;`,
    ].join('\n');
  });

  const header = [
    `// Generated by RuneArch: Zod schemas and TypeScript types for the API models${options.featureName ? ` of feature ${options.featureName}` : ''}.`,
    '// Requires zod>=4. Parse with e.g. OrderDto.parse(json); types come from z.infer.',
  ].join('\n');
  return `${[header, "import { z } from 'zod';", ...schemas].join('\n\n')}\n`;
}
