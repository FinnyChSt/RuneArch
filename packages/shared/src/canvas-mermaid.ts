import type { CanvasDoc, CanvasEdge, CanvasNode, FeatureRole } from './canvas';
import type { FeatureRoles } from './feature-scope';
import { elementIdOf } from './wireframe';
import { FLOW_SVG_COLORS } from './canvas-svg';

/*
 * The canvas as a Mermaid `flowchart`: nodes with a shape per type, frames as subgraphs, link edges
 * labelled with their kind (or label), FKs as dotted links. Renders in GitHub/GitLab markdown and
 * docs. Pen strokes are left out. With a flow, its steps get numbers and the flow's color.
 */

type Doc = Pick<CanvasDoc, 'nodes' | 'edges' | 'flows'>;

/** Mermaid label text: quotes and markup-ish characters as entities, newlines as <br/> */
const label = (s: string) =>
  s
    .replaceAll('&', '#amp;')
    .replaceAll('"', '#quot;')
    .replaceAll('<', '#lt;')
    .replaceAll('>', '#gt;')
    .replaceAll('|', '#124;')
    .replaceAll('\n', '<br/>');

const CLASS: Partial<Record<CanvasNode['type'], string>> = {
  screen: 'fe',
  component: 'fe',
  store: 'fe',
  endpoint: 'be',
  service: 'be',
  job: 'be',
  external: 'be',
  table: 'db',
  sketch: 'sketch',
};

const ROLE_TAG: Record<FeatureRole, string> = { added: 'NEW', changed: 'CHANGED', uses: 'EXISTING', removed: 'REMOVED' };

/** `id + shape(text)`, one shape per node type; `tag` adds a small line under the text (a feature role) */
function shape(id: string, node: CanvasNode, tag?: string): string | null {
  const plain = baseShape(id, node);
  if (!plain || !tag) return plain;
  // The label is the last quoted text of the shape; the tag goes inside it
  const at = plain.lastIndexOf('"');
  return `${plain.slice(0, at)}<br/><small>${tag}</small>${plain.slice(at)}`;
}

function baseShape(id: string, node: CanvasNode): string | null {
  switch (node.type) {
    case 'screen':
      return `${id}["${label(node.label || 'Screen')}${node.data.route ? `<br/><small>${label(node.data.route)}</small>` : ''}"]`;
    case 'component':
      return `${id}(["${label(node.label || 'Component')}"])`;
    case 'store':
      return `${id}[("${label(node.label || 'Store')}")]`;
    case 'endpoint':
      return `${id}[/"${label(`${node.data.method} ${node.data.path}`)}"/]`;
    case 'service':
      return `${id}[["${label(node.label || 'Service')}"]]`;
    case 'job':
      return `${id}{{"${label(node.label || 'Job')}"}}`;
    case 'external':
      return `${id}>"${label(node.label || 'External')}"]`;
    case 'table':
      return `${id}[("${label(node.label || 'table')}")]`;
    case 'sketch':
      if (node.data.shape === 'freehand') return null;
      return node.data.shape === 'ellipse'
        ? `${id}(("${label(node.data.text || ' ')}"))`
        : `${id}["${label(node.data.text || ' ')}"]`;
    case 'frame':
      return null;
  }
}

const CRUD_LETTER = { create: 'C', read: 'R', update: 'U', delete: 'D' } as const;

function edgeText(e: CanvasEdge, element: string | undefined): string {
  if (e.kind === 'fk') return 'FK';
  const base = e.label ?? (e.crud?.length ? e.crud.map((op) => CRUD_LETTER[op]).join('') : e.kind === 'arrow' ? '' : e.kind);
  return element ? `${element}: ${base}`.replace(/: $/, '') : base;
}

export type MermaidFlowchartOptions = {
  flowId?: string;
  /** Mark a feature's items: a role line on each node, its added and changed edges in its color */
  feature?: { name: string; color?: string; roles: FeatureRoles };
};

export function toMermaidFlowchart(doc: Doc, options: MermaidFlowchartOptions = {}): string {
  const { feature } = options;
  const roleOf = (kind: 'node' | 'edge', id: string) => feature?.roles.get(`${kind}:${id}`);
  const ids = new Map(doc.nodes.map((n, i) => [n.id, `n${i + 1}`]));
  const shapes = new Map(
    doc.nodes.map((n) => {
      const role = n.type === 'frame' ? undefined : roleOf('node', n.id);
      return [n.id, shape(ids.get(n.id)!, n, role && ROLE_TAG[role])];
    }),
  );
  const out = [`%% Generated by RuneArch${feature ? `. Feature: ${feature.name}` : ''}`, 'flowchart LR'];

  // Frames become subgraphs holding their children
  for (const frame of doc.nodes.filter((n) => n.type === 'frame')) {
    const children = doc.nodes.filter((n) => n.parentId === frame.id && shapes.get(n.id));
    out.push(`  subgraph ${ids.get(frame.id)}["${label(frame.label || 'Frame')}"]`);
    for (const c of children) out.push(`    ${shapes.get(c.id)}`);
    out.push('  end');
  }
  for (const n of doc.nodes) if (!n.parentId && shapes.get(n.id)) out.push(`  ${shapes.get(n.id)}`);

  const flow = options.flowId ? doc.flows.find((f) => f.id === options.flowId) : undefined;
  const steps = new Map(flow?.steps.map((s, i) => [s.edgeId, i + 1]));
  const nodes = new Map(doc.nodes.map((n) => [n.id, n]));
  const drawn: string[] = [];
  for (const e of doc.edges) {
    if (!shapes.get(e.source) || !shapes.get(e.target)) continue;
    const source = nodes.get(e.source);
    const elementId = elementIdOf(e.sourceHandle);
    const element =
      elementId !== null && source?.type === 'screen'
        ? source.data.wireframe?.elements.find((el) => el.id === elementId)?.text?.trim()
        : undefined;
    const step = steps.get(e.id);
    const text = [step && `${step}.`, edgeText(e, element)].filter(Boolean).join(' ');
    const arrow = e.kind === 'fk' ? '-.->' : e.kind === 'navigates' ? '-.->' : '-->';
    out.push(`  ${ids.get(e.source)} ${arrow}${text ? `|"${label(text)}"|` : ''} ${ids.get(e.target)}`);
    drawn.push(e.id);
  }

  out.push(
    '  classDef fe stroke:#6FC3B8,stroke-width:2px',
    '  classDef be stroke:#A79BE0,stroke-width:2px',
    '  classDef db stroke:#E0B46F,stroke-width:2px',
    '  classDef sketch fill:#F3E9C8,stroke:#D9CFB8,color:#2B2618',
  );
  const byClass = new Map<string, string[]>();
  for (const n of doc.nodes) {
    const cls = CLASS[n.type];
    if (cls && shapes.get(n.id)) byClass.set(cls, [...(byClass.get(cls) ?? []), ids.get(n.id)!]);
  }
  for (const [cls, members] of byClass) out.push(`  class ${members.join(',')} ${cls}`);

  if (flow) {
    const color = FLOW_SVG_COLORS[flow.color ?? ''] ?? FLOW_SVG_COLORS.violet!;
    const flowLinks = drawn.flatMap((id, i) => (steps.has(id) ? [i] : []));
    if (flowLinks.length) out.push(`  linkStyle ${flowLinks.join(',')} stroke:${color},stroke-width:3px`);
  }
  if (feature && !flow) {
    const color = FLOW_SVG_COLORS[feature.color ?? ''] ?? FLOW_SVG_COLORS.violet!;
    out.push(
      `  classDef featureNew stroke:${color},stroke-width:3px`,
      `  classDef featureChanged stroke:${color},stroke-width:3px,stroke-dasharray:6 3`,
      '  classDef featureRemoved stroke:#C95454,stroke-width:2px,stroke-dasharray:4 4',
    );
    const ROLE_CLASS: Partial<Record<FeatureRole, string>> = { added: 'featureNew', changed: 'featureChanged', removed: 'featureRemoved' };
    const members = new Map<string, string[]>();
    for (const n of doc.nodes) {
      const cls = n.type === 'frame' ? undefined : ROLE_CLASS[roleOf('node', n.id) ?? 'uses'];
      if (cls && shapes.get(n.id)) members.set(cls, [...(members.get(cls) ?? []), ids.get(n.id)!]);
    }
    for (const [cls, list] of members) out.push(`  class ${list.join(',')} ${cls}`);
    const accent = drawn.flatMap((id, i) => (['added', 'changed'].includes(roleOf('edge', id) ?? '') ? [i] : []));
    const removed = drawn.flatMap((id, i) => (roleOf('edge', id) === 'removed' ? [i] : []));
    if (accent.length) out.push(`  linkStyle ${accent.join(',')} stroke:${color},stroke-width:2.5px`);
    if (removed.length) out.push(`  linkStyle ${removed.join(',')} stroke:#C95454,stroke-dasharray:4 4`);
  }
  return `${out.join('\n')}\n`;
}
