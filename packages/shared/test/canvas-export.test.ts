import { describe, expect, it } from 'vitest';
import {
  CANVAS_EXPORTS,
  CANVAS_FILE_FORMAT,
  canvasExportByExtension,
  CanvasDoc,
  canvasToSvg,
  emptyCanvas,
  estimateNodeSize,
  toCanvasJson,
  toMermaidFlowchart,
} from '../src';

const at = (x: number, y: number) => ({ x, y });

/** A bit of everything: a lane with a screen whose button calls an endpoint, tables with an FK, sketches and a flow */
const doc = CanvasDoc.parse({
  ...emptyCanvas(),
  models: [{ id: 'm', name: 'CreateOrderDto', fields: [] }],
  nodes: [
    { id: 'lane', type: 'frame', label: 'Frontend "web"', position: at(-40, -60), size: { width: 400, height: 360 }, data: { lane: 'frontend' } },
    {
      id: 'cart',
      type: 'screen',
      label: 'Cart <main>',
      parentId: 'lane',
      position: at(40, 60),
      data: {
        route: '/cart',
        wireframe: { device: 'mobile', elements: [{ id: 'go', kind: 'button', rect: { x: 0, y: 0, w: 12, h: 5 }, text: 'Place order' }] },
      },
    },
    {
      id: 'post',
      type: 'endpoint',
      position: at(500, 0),
      data: { method: 'POST', path: '/orders', spec: { summary: 'Place an order', requestBody: { type: { kind: 'ref', modelId: 'm' } } } },
    },
    { id: 'svc', type: 'service', label: 'OrderService', position: at(800, 0), data: { methods: ['create'] } },
    { id: 'orders', type: 'table', label: 'orders', position: at(800, 300), data: { columns: [{ id: 'o1', name: 'id', type: 'uuid', primaryKey: true }, { id: 'o2', name: 'user_id', type: 'uuid' }] } },
    { id: 'users', type: 'table', label: 'users', position: at(500, 300), data: { columns: [{ id: 'u1', name: 'id', type: 'uuid', primaryKey: true }] } },
    { id: 'note', type: 'sketch', position: at(0, 400), size: { width: 180, height: 160 }, data: { shape: 'sticky', text: 'Retry & idempotency' } },
    { id: 'pen', type: 'sketch', position: at(200, 400), size: { width: 50, height: 50 }, data: { shape: 'freehand', points: [[0, 0, 0.5], [40, 40, 0.5]] } },
  ],
  edges: [
    { id: 'click', kind: 'calls', source: 'cart', target: 'post', sourceHandle: 'el:go' },
    { id: 'call', kind: 'calls', source: 'post', target: 'svc' },
    { id: 'write', kind: 'writes', source: 'svc', target: 'orders', crud: ['create'] },
    { id: 'read', kind: 'reads', source: 'orders', target: 'svc' },
    { id: 'fk', kind: 'fk', source: 'orders', target: 'users', data: { sourceColumnId: 'o2', targetColumnId: 'u1' } },
    { id: 'hint', kind: 'arrow', source: 'note', target: 'cart' },
  ],
  flows: [{ id: 'checkout', name: 'Checkout', color: 'teal', steps: [{ edgeId: 'click' }, { edgeId: 'call' }, { edgeId: 'write' }] }],
});

describe('canvasToSvg', () => {
  it('draws every node and edge, with frame children at absolute positions', () => {
    const svg = canvasToSvg(doc);
    expect(svg).toMatch(/^<svg xmlns="http:\/\/www.w3.org\/2000\/svg" width="[\d.]+" height="[\d.]+" viewBox="/);
    for (const s of ['Frontend &quot;web&quot;', 'Cart &lt;main&gt;', '/orders', 'OrderService', 'user_id', 'Retry &amp; idempotency', 'Place order'])
      expect(svg).toContain(s);
    expect(svg).not.toContain('<main>');
    // The screen sits in the lane: 40 + (-40) = 0
    expect(svg).toContain('<rect x="0" y="0" width=');
    // Six edges (marker shapes in <defs> aside); the pen stroke is a polyline
    expect(svg.match(/<path d="[^"]*" fill="none"/g)).toHaveLength(6);
    expect(svg).toContain('marker-start="url(#crow)"');
    expect(svg).toContain('<polyline');
    expect(svg).toContain('>C<'); // CRUD label
  });

  it('highlights a flow: numbered steps in its color, the rest faded', () => {
    const svg = canvasToSvg(doc, { flowId: 'checkout', theme: 'dark' });
    expect(svg).toContain('Flow: Checkout');
    expect(svg).toContain('fill="#1B2635"'); // dark background
    for (const n of [1, 2, 3]) expect(svg).toContain(`dominant-baseline="central">${n}</text>`);
    expect(svg.match(/stroke="#4FB3A6"/g)).toHaveLength(3);
    expect(svg).toContain('opacity="0.25"');
  });

  it('uses measured sizes when given, and estimates them otherwise', () => {
    const measured = canvasToSvg(doc, { sizes: { svc: { width: 321, height: 77 } } });
    expect(measured).toContain('width="321" height="77"');
    const orders = doc.nodes.find((n) => n.id === 'orders')!;
    expect(estimateNodeSize(orders)).toEqual({ width: 208, height: 4 + 28 + 8 + 2 * 22 });
    expect(canvasToSvg({ ...emptyCanvas() })).toContain('Empty canvas');
  });
});

describe('toMermaidFlowchart', () => {
  it('renders nodes by type, frames as subgraphs and labelled links', () => {
    expect(toMermaidFlowchart(doc)).toMatchInlineSnapshot(`
      "%% Generated by RuneArch
      flowchart LR
        subgraph n1["Frontend #quot;web#quot;"]
          n2["Cart #lt;main#gt;<br/><small>/cart</small>"]
        end
        n3[/"POST /orders"/]
        n4[["OrderService"]]
        n5[("orders")]
        n6[("users")]
        n7["Retry #amp; idempotency"]
        n2 -->|"Place order: calls"| n3
        n3 -->|"calls"| n4
        n4 -->|"C"| n5
        n5 -->|"reads"| n4
        n5 -.->|"FK"| n6
        n7 --> n2
        classDef fe stroke:#6FC3B8,stroke-width:2px
        classDef be stroke:#A79BE0,stroke-width:2px
        classDef db stroke:#E0B46F,stroke-width:2px
        classDef sketch fill:#F3E9C8,stroke:#D9CFB8,color:#2B2618
        class n2 fe
        class n3,n4 be
        class n5,n6 db
        class n7 sketch
      "
    `);
  });

  it('numbers and colors the steps of a flow', () => {
    const out = toMermaidFlowchart(doc, { flowId: 'checkout' });
    expect(out).toContain('n2 -->|"1. Place order: calls"| n3');
    expect(out).toContain('n4 -->|"3. C"| n5');
    expect(out).toContain('linkStyle 0,1,2 stroke:#4FB3A6,stroke-width:3px');
  });
});

describe('canvas exports', () => {
  it('JSON is a RuneArch file that parses back to the same document', () => {
    const file = JSON.parse(toCanvasJson(doc));
    expect(file.format).toBe(CANVAS_FILE_FORMAT);
    expect(file.schemaVersion).toBe(1);
    expect(CanvasDoc.parse(file.doc)).toEqual(doc);
  });

  it('finds formats by extension', () => {
    expect(canvasExportByExtension('svg')).toBe(CANVAS_EXPORTS.svg);
    expect(canvasExportByExtension('mmd')).toBe(CANVAS_EXPORTS.mermaid);
    expect(canvasExportByExtension('json')).toBe(CANVAS_EXPORTS.json);
    expect(canvasExportByExtension('png')).toBeUndefined();
  });
});
